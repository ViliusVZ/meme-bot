# Plan 03: the two jingles, encoded once into WebM Opus (the format Edge's voices come in: 48 kHz,
# 20 ms frames), loudness matched to the voices. The image has no encoder, so the bot carries the
# result as src/jingles.ts (base64; the filesystem is read-only and holds no assets).
#   python -I scripts/encode_jingles.py <dir with jingle1-arpeggio.wav and jingle2-beepbeep.wav>
# Needs PyAV (pip install av numpy). Speech from Edge measures about -20 dB gated RMS (100 ms
# blocks); tones sound louder than speech at the same level, so the jingles go to -23 dB.
import base64, io, sys, wave
import av, numpy as np

TARGET = -23.0  # dB, gated RMS over 100 ms blocks
SRC = sys.argv[1]

def gated_rms(a, sr):
    b = int(sr * 0.1)
    ms = np.array([np.mean(a[i:i + b] ** 2) for i in range(0, len(a) - b + 1, b // 2)])
    ms = ms[ms > 10 ** (-60 / 10)]
    return 10 * np.log10(np.mean(ms))

encoded = {}
for name in ("jingle1-arpeggio", "jingle2-beepbeep"):
    w = wave.open(f"{SRC}/{name}.wav")
    assert w.getframerate() == 48000 and w.getnchannels() == 1 and w.getsampwidth() == 2
    a = np.frombuffer(w.readframes(w.getnframes()), dtype=np.int16).astype(np.float64) / 32768
    gain = 10 ** ((TARGET - gated_rms(a, 48000)) / 20)
    a = np.clip(a * gain, -1, 1)
    pcm = (a * 32767).astype(np.int16)
    buf = io.BytesIO()
    out = av.open(buf, "w", format="webm")
    s = out.add_stream("libopus", rate=48000, layout="mono")
    s.bit_rate = 64000
    s.codec_context.options = {"frame_duration": "20", "application": "audio"}
    for i in range(0, len(pcm), 960):
        chunk = pcm[i:i + 960]
        if len(chunk) < 960: chunk = np.pad(chunk, (0, 960 - len(chunk)))
        f = av.AudioFrame.from_ndarray(chunk.reshape(1, -1), format="s16", layout="mono")
        f.sample_rate = 48000
        f.pts = i
        for p in s.encode(f): out.mux(p)
    for p in s.encode(None): out.mux(p)
    out.close()
    encoded[name] = base64.b64encode(buf.getvalue()).decode()
    print(name, f"gain {20 * np.log10(gain):+.1f} dB -> {gated_rms(a, 48000):.1f} dB, peak {20 * np.log10(np.max(np.abs(a))):.1f} dBFS")

with open("src/jingles.ts", "w", encoding="utf8", newline="\n") as f:
    f.write("// Generated by scripts/encode_jingles.py (plan 03): the two jingles as WebM Opus, base64. Don't edit.\n")
    f.write(f'export const NIGHT_JINGLE = "{encoded["jingle1-arpeggio"]}";\n')
    f.write(f'export const BEEP = "{encoded["jingle2-beepbeep"]}";\n')
